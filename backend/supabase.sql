-- tablas del proyecto hectaria (ep3)
-- pegar esto completo en el sql editor de supabase
-- no activamos rls para que la app pueda usar la anon key sin login de supabase

create table usuarios (
  correo text primary key,
  nombre text not null,
  clave text not null,
  tipo text not null default 'productor',
  cobertura text,
  capacidad int,
  experiencia int
);

create table prestadores (
  id int generated by default as identity primary key,
  correo text unique,
  nombre text not null,
  zona text not null,
  servicios text not null,
  cultivos text not null default '',
  capacidad int not null,
  experiencia int not null default 3,
  disponible boolean not null default true,
  evaluacion real not null default 4
);

create table necesidades (
  id bigint generated always as identity primary key,
  correo_usuario text not null,
  zona text not null,
  cultivo text not null,
  servicio text not null,
  superficie int not null,
  fecha timestamp default now()
);

create table vinculaciones (
  id bigint generated always as identity primary key,
  correo_usuario text not null,
  prestador_id int,
  prestador_nombre text,
  compatibilidad int,
  servicio text,
  cultivo text,
  fecha timestamp default now()
);

-- el id arranca despues de los prestadores semilla para no chocar
alter table prestadores alter column id restart with 100;

